    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if (txfNombre.getText().trim().isEmpty() || 
            txfApellidos.getText().trim().isEmpty() || 
            txfCorreoElectronico.getText().trim().isEmpty() || 
            txfTelefonoFijo.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, 
                    "Por favor, llene todos los campos obligatorios.", 
                    "Advertencia", 
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        Proveedor p = serializarProveedor();
        if (proveedorModificar == null) {
            int resultado = ProveedorDAO.insertar(p);
            if (resultado > 0) {
                JOptionPane.showMessageDialog(this, "Proveedor guardado con éxito.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                this.dispose();
            }
        } else {
            p.setIdProveedor(proveedorModificar.getIdProveedor());
            int actualizado = ProveedorDAO.modificar(p);
            if (actualizado > 0) {
                JOptionPane.showMessageDialog(this, "Proveedor actualizado con éxito.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                this.dispose();
            }
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

