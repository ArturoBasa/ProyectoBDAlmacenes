    private Proveedor serializarProveedor() {
        Proveedor p = new Proveedor();
        p.setRazonSocial(txfNombre.getText().trim());
        p.setRFCProveedor(txfApellidos.getText().trim());
        p.setDomicilioFiscal(txfCorreoElectronico.getText().trim());
        p.setTelefono(txfTelefonoFijo.getText().trim());
        return p;
    }

    private void llenarParaModificar(Proveedor p) {
        txfNombre.setText(p.getRazonSocial());
        txfApellidos.setText(p.getRFCProveedor());
        txfCorreoElectronico.setText(p.getDomicilioFiscal());
        txfTelefonoFijo.setText(p.getTelefono());
    }


