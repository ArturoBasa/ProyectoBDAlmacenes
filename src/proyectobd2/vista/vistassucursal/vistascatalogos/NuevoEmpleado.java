    private void llenarComboBoxSucursales(List<Sucursal> sucursales) {
        cbxSucursal.removeAllItems();
        for (Sucursal s : sucursales) {
            cbxSucursal.addItem(s.toString());
        }
    }

    private void llenarComboBoxDepartamentos(List<Departamento> departamentos) {
        cbxDepartamento.removeAllItems();
        for (Departamento d : departamentos) {
            cbxDepartamento.addItem(d.toString());
        }
    }
    
    private void llenarComboBoxRol() {
        cbxRol.removeAllItems();
        try{
            if("Usuario central".equals(rol)){
                roles = RolDAO.obtenerListaRoles();
                for (Rol r : roles) {
                    cbxRol.addItem(r.toString());
                }
            }
            if("Usuario sucursal".equals(rol)){
                roles = RolDAO.obtenerListaRolesSucursal();
                for (Rol r : roles) {
                    cbxRol.addItem(r.toString());
                }
            }
        }catch(SQLException e){
            JOptionPane.showMessageDialog(this, "Error de carga de roles", "Error", JOptionPane.ERROR_MESSAGE);
        }
       
    }
    
    private Empleado serializarEmpleado() {
        Empleado empleado = new Empleado();
        empleado.setNombre(txfNombre.getText().trim());
        empleado.setApellidos(txfApellidos.getText().trim());
        empleado.setCorreoElectronico(txfCorreoElectronico.getText().trim());
        String tlfFijo = txfTelefonoFijo.getText().trim();
        if(tlfFijo.isEmpty()){
            empleado.setTelefonoFijo(null);
        }else{
            empleado.setTelefonoFijo(tlfFijo);
        }
        empleado.setTelefonoCelular(txfTelefonoCel.getText().trim());
        
        if(empleadoModificar == null && !txfContraseña.getText().isBlank()){
            empleado.setContrasenia(hashPassword(txfContraseña.getText().trim()));
        }
        if(empleadoModificar != null && !txfContraseña.getText().isBlank()){
            empleado.setContrasenia(hashPassword(txfContraseña.getText().trim()));
        }
        if(empleadoModificar != null && txfContraseña.getText().isBlank()){
            empleado.setContrasenia(null);
        }
        int indiceSucursal = cbxSucursal.getSelectedIndex();
        if (indiceSucursal != -1) {
            Sucursal sucursalSeleccionada = listaSucursales.get(indiceSucursal);
            empleado.setIdSucursal(sucursalSeleccionada.getIdSucursal());
            empleado.setSucursal(sucursalSeleccionada.getNombreSucursal()); 
        }
        int indiceDepartamento = cbxDepartamento.getSelectedIndex();
        if (indiceDepartamento != -1) {
            Departamento departamentoSeleccionado = listaDepartamentos.get(indiceDepartamento);
            empleado.setIdDepartamentoEncar(departamentoSeleccionado.getIdDepartamento());
        }
        int indiceRol = cbxRol.getSelectedIndex();
        if (indiceRol != -1) {
            Rol rolSeleccionado = roles.get(indiceRol);
            empleado.setIdRol(rolSeleccionado.getIdRol());
        }
        empleado.setFechaRegistro(new java.sql.Date(System.currentTimeMillis()));
        return empleado;
    }
    
    private void llenarParaModificar(Empleado empleado){
        txfNombre.setText(empleado.getNombre());
        txfApellidos.setText(empleado.getApellidos());
        txfCorreoElectronico.setText(empleado.getCorreoElectronico());
        txfTelefonoFijo.setText(empleado.getTelefonoFijo());
        txfTelefonoCel.setText(empleado.getTelefonoCelular());
        for (int i = 0; i < listaSucursales.size(); i++) {
            if (listaSucursales.get(i).getIdSucursal() == empleado.getIdSucursal()) {
                cbxSucursal.setSelectedIndex(i);
                break;
            }
        }
        for (int i = 0; i < listaDepartamentos.size(); i++) {
            if (listaDepartamentos.get(i).getIdDepartamento() == empleado.getIdDepartamentoEncar()) {
                cbxDepartamento.setSelectedIndex(i);
                break;
            }
        }
        for (int i = 0; i < roles.size(); i++) {
            if (roles.get(i).getIdRol() == empleado.getIdRol()) {
                cbxRol.setSelectedIndex(i);
                break;
            }
        }
    }

