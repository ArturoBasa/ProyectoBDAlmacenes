    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if (txfNombre.getText().trim().isEmpty() || 
            txfApellidos.getText().trim().isEmpty() || 
            txfCorreoElectronico.getText().trim().isEmpty() || 
            cbxSucursal.getSelectedIndex() == -1 ||
            cbxDepartamento.getSelectedIndex() == -1 ||
            cbxRol.getSelectedIndex() == -1){
            JOptionPane.showMessageDialog(this, 
                    "Por favor, llene todos los campos obligatorios y seleccione las listas.", 
                    "Advertencia", 
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        Empleado empleado = serializarEmpleado();
        
        if (empleadoModificar == null) {
            if (txfContraseña.getText().trim().isEmpty()){
                JOptionPane.showMessageDialog(this, 
                        "La contraseña es obligatoria para un nuevo empleado.", 
                        "Advertencia", 
                        JOptionPane.WARNING_MESSAGE);
                return;
            }
            int resultado = EmpleadoDAO.insertar(empleado);
            if (resultado > 0) {
                JOptionPane.showMessageDialog(this, "Empleado guardado", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                this.dispose();
            }
        } else {
            empleado.setIdEmpleado(empleadoModificar.getIdEmpleado());
            if (empleado.getContrasenia() == null || empleado.getContrasenia().isEmpty()) {
                int actualizado = EmpleadoDAO.modificarsincontra(empleado);
                if (actualizado > 0) {
                    JOptionPane.showMessageDialog(this, "Empleado actualizado (sin contraseña)", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                    this.dispose();
                }
            } else {
                int actualizado = EmpleadoDAO.modificarConCOntra(empleado);
                if (actualizado > 0) {
                    JOptionPane.showMessageDialog(this, "Empleado actualizado (con contraseña)", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                    this.dispose();
                }
            }
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

